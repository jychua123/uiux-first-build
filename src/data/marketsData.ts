function seededRandom(seed: number): () => number {
  let s = seed % 2147483647;
  if (s <= 0) s += 2147483646;
  return () => {
    s = (s * 16807) % 2147483647;
    return (s - 1) / 2147483646;
  };
}

function hashString(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

function buildTimeLabel(index: number, total: number, tf: Timeframe): string {
  if (tf === '1D') {
    const startMinutes = 9 * 60 + 30;
    const step = (6.5 * 60) / Math.max(total - 1, 1);
    const mins = Math.round(startMinutes + index * step);
    const hh = Math.floor(mins / 60)
      .toString()
      .padStart(2, '0');
    const mm = (mins % 60).toString().padStart(2, '0');
    return `${hh}:${mm}`;
  }
  if (tf === '5D') {
    const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri'];
    const dayIdx = Math.min(4, Math.floor((index / total) * 5));
    return `${days[dayIdx]} ${(9 + (index % 7)).toString().padStart(2, '0')}:00`;
  }
  if (tf === '1M') {
    const day = Math.max(1, Math.round((index / Math.max(total - 1, 1)) * 29) + 1);
    return `Nov ${day}`;
  }
  if (tf === '6M' || tf === 'YTD' || tf === '1Y') {
    const months = ['Dec', 'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov'];
    const mIdx = Math.min(months.length - 1, Math.floor((index / total) * months.length));
    return `${months[mIdx]} '${mIdx === 0 ? '25' : '26'}`;
  }
  const startYear = tf === '5Y' ? 2021 : 2016;
  const span = tf === '5Y' ? 5 : 10;
  const yr = startYear + Math.floor((index / Math.max(total - 1, 1)) * span);
  const q = (index % 4) + 1;
  return `Q${q} ${yr}`;
}

export function generateOhlcSeries(
  symbol: MarketSymbol,
  timeframe: Timeframe
): OhlcPoint[] {
  const cfg = TIMEFRAME_CONFIG[timeframe];
  const seed = hashString(`${symbol.id}-${timeframe}`);
  const rand = seededRandom(seed);

  const endPrice = symbol.price;
  const baseDeltaPct =
    timeframe === '1D'
      ? symbol.changePercent / 100
      : (symbol.changePercent / 100) * cfg.driftMultiplier * 0.45 +
        (symbol.rating.includes('Buy') ? 0.04 : symbol.rating.includes('Sell') ? -0.03 : 0.015) *
          (cfg.driftMultiplier * 0.25);

  const clampedDeltaPct = Math.max(-0.55, Math.min(1.6, baseDeltaPct));
  const startPrice =
    timeframe === '1D'
      ? symbol.prevClose
      : endPrice / (1 + clampedDeltaPct);

  const points: OhlcPoint[] = [];
  const count = cfg.points;

  // Build Brownian bridge so endpoints match startPrice -> endPrice cleanly
  const rawSteps: number[] = [0];
  for (let i = 1; i < count; i++) {
    const shock = (rand() - 0.5) * 2 * cfg.volatility;
    rawSteps.push(rawSteps[i - 1] + shock);
  }
  const endOffset = rawSteps[count - 1];

  let prevClose = startPrice;
  for (let i = 0; i < count; i++) {
    const t = i / Math.max(count - 1, 1);
    const bridgeNoise = rawSteps[i] - t * endOffset;
    const baseCurve = startPrice + (endPrice - startPrice) * t;
    const closeVal =
      i === count - 1
        ? endPrice
        : Math.max(0.0001, baseCurve * (1 + bridgeNoise));

    const openVal = i === 0 ? startPrice : prevClose;
    const bodyMax = Math.max(openVal, closeVal);
    const bodyMin = Math.min(openVal, closeVal);
    const wickScale = closeVal * cfg.volatility * 0.55;
    const highVal = bodyMax + rand() * wickScale;
    const lowVal = Math.max(0.0001, bodyMin - rand() * wickScale);

    points.push({
      time: buildTimeLabel(i, count, timeframe),
      open: Number(openVal.toFixed(symbol.decimals)),
      high: Number(highVal.toFixed(symbol.decimals)),
      low: Number(lowVal.toFixed(symbol.decimals)),
      close: Number(closeVal.toFixed(symbol.decimals)),
      volume: Math.round(40 + rand() * 140),
    });

    prevClose = closeVal;
  }

  return points;
}

export function formatPrice(value: number, decimals = 2): string {
  return value.toLocaleString('en-US', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  });
}

export function getSymbolsByCategory(cat: MarketCategory): MarketSymbol[] {
  return MARKET_SYMBOLS.filter((s) => s.category === cat);
}
